package storage

import (
	"database/sql"
	"fmt"
	"io/fs"
	"strings"
	"unicode"
)

// SchemaDocumentation runs the production migrations in an isolated, temporary
// SQLite database. A nil source uses the application's embedded migrations.
// Custom sources must contain migrations/*.sql, just like the embedded FS.
func SchemaDocumentation(source fs.FS) (string, string, error) {
	if source == nil {
		source = migrations
	}
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		return "", "", err
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	if _, err = db.Exec("PRAGMA foreign_keys = ON"); err != nil {
		return "", "", err
	}
	if err = applyMigrationsFrom(db, source); err != nil {
		return "", "", err
	}
	return describeSchema(db)
}

// Mermaid identifiers are encoded when necessary, preserving ordinary names.
func mermaidName(name string) string {
	valid := name != "" && !strings.HasPrefix(name, "encoded_")
	for i, r := range name {
		if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			valid = false
		}
	}
	if valid {
		return name
	}
	return fmt.Sprintf("encoded_%x", name)
}

func describeSchema(db *sql.DB) (string, string, error) {
	rows, err := db.Query(`SELECT type, name, sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\_%' ESCAPE '\' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'view' THEN 1 WHEN 'index' THEN 2 ELSE 3 END, name`)
	if err != nil {
		return "", "", err
	}
	type object struct{ kind, name, ddl string }
	var objects []object
	for rows.Next() {
		var o object
		if err = rows.Scan(&o.kind, &o.name, &o.ddl); err != nil {
			rows.Close()
			return "", "", err
		}
		objects = append(objects, o)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return "", "", err
	}
	var schema, diagram strings.Builder
	schema.WriteString("-- Generated by npm run db:docs. Do not edit.\n")
	diagram.WriteString("# Database schema\n\nGenerated by `npm run db:docs` from all SQLite migrations. Do not edit.\n\nThe SQL file includes tables, views, explicit indexes and triggers. SQLite's internal objects and migration data are excluded.\n\n```mermaid\nerDiagram\n")
	var relationships []string
	for _, o := range objects {
		schema.WriteString(strings.TrimRight(strings.TrimSpace(o.ddl), ";") + ";\n\n")
		if o.kind != "table" {
			continue
		}
		columns, err := db.Query(`SELECT name, type, pk FROM pragma_table_xinfo(?) WHERE hidden != 1 ORDER BY cid`, o.name)
		if err != nil {
			return "", "", err
		}
		type column struct {
			name, typ string
			pk        int
		}
		var cols []column
		for columns.Next() {
			var c column
			if err = columns.Scan(&c.name, &c.typ, &c.pk); err != nil {
				columns.Close()
				return "", "", err
			}
			cols = append(cols, c)
		}
		err = columns.Err()
		columns.Close()
		if err != nil {
			return "", "", err
		}
		foreignKeys, err := db.Query(`SELECT id, seq, "table", "from", "to" FROM pragma_foreign_key_list(?) ORDER BY id, seq`, o.name)
		if err != nil {
			return "", "", err
		}
		fk := map[string]bool{}
		for foreignKeys.Next() {
			var id, seq int
			var parent, from string
			var to sql.NullString
			if err = foreignKeys.Scan(&id, &seq, &parent, &from, &to); err != nil {
				foreignKeys.Close()
				return "", "", err
			}
			fk[from] = true
			// One edge per constraint; composite columns remain marked FK below.
			if seq == 0 {
				relationships = append(relationships, fmt.Sprintf("    %s |o..o{ %s : fk_%d\n", mermaidName(parent), mermaidName(o.name), id))
			}
		}
		err = foreignKeys.Err()
		foreignKeys.Close()
		if err != nil {
			return "", "", err
		}
		fmt.Fprintf(&diagram, "    %s {\n", mermaidName(o.name))
		for _, c := range cols {
			typ := strings.Map(func(r rune) rune {
				if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
					return r
				}
				return '_'
			}, c.typ)
			if typ == "" {
				typ = "untyped"
			}
			var keys []string
			if c.pk > 0 {
				keys = append(keys, "PK")
			}
			if fk[c.name] {
				keys = append(keys, "FK")
			}
			key := ""
			if len(keys) > 0 {
				key = " " + strings.Join(keys, ",")
			}
			fmt.Fprintf(&diagram, "        %s %s%s\n", typ, mermaidName(c.name), key)
		}
		diagram.WriteString("    }\n")
	}
	for _, edge := range relationships {
		diagram.WriteString(edge)
	}
	diagram.WriteString("```\n\nRelationships show declared foreign keys conservatively (zero or one parent, zero or many children); uniqueness and requiredness are defined in [schema.sql](schema.sql). Encoded identifiers use `encoded_` followed by the UTF-8 name in hexadecimal. Views appear only in the SQL schema.\n")
	return diagram.String(), strings.TrimRight(schema.String(), "\n") + "\n", nil
}
